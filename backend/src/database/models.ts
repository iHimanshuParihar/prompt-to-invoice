export type CurrencyCode = 'USD' | 'EUR' | 'GBP' | 'CAD' | 'AUD';

export type InvoiceStatus = 'draft' | 'sent' | 'paid' | 'overdue' | 'cancelled';

export interface User {
  id: string;
  name: string;
  email: string;
  passwordHash: string;
  avatarUrl?: string;
  role: 'owner' | 'admin' | 'member';
  defaultCurrency: CurrencyCode;
  createdAt: string;
  updatedAt: string;
}

export interface Session {
  id: string; // Session Token (UUID)
  userId: string;
  expiresAt: string;
  createdAt: string;
  userAgent?: string;
}

export interface BusinessProfile {
  id: string;
  userId: string; // Multi-tenant owner
  name: string;
  legalName?: string;
  email: string;
  phone?: string;
  website?: string;
  address: string;
  city: string;
  country: string;
  postalCode: string;
  taxNumber?: string; // EIN or VAT ID
  bankDetails?: {
    bankName: string;
    accountNumber?: string;
    routingNumber?: string;
    iban?: string;
    bic?: string;
  };
  logoUrl?: string;
  currency: CurrencyCode;
  defaultPaymentTermsDays: number;
  isDefault: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface Client {
  id: string;
  userId: string; // Multi-tenant owner
  name: string;
  companyName: string;
  email: string;
  phone?: string;
  address?: string;
  city?: string;
  country?: string;
  taxNumber?: string;
  currency: CurrencyCode;
  notes?: string;
  totalBilled: number;
  outstandingBalance: number;
  createdAt: string;
  updatedAt: string;
}

export interface InvoiceItem {
  id: string;
  description: string;
  quantity: number;
  unitPrice: number;
  taxRate: number; // percentage (e.g. 20 for 20%)
  total: number;
}

export interface PaymentRecord {
  id: string;
  amount: number;
  date: string;
  method: 'stripe' | 'wire' | 'cash' | 'credit_card' | 'paypal' | 'check';
  note?: string;
  transactionReference?: string;
}

export interface Invoice {
  id: string;
  userId: string; // Multi-tenant owner
  invoiceNumber: string;
  profileId: string;
  clientId: string;
  clientName: string;
  clientEmail: string;
  clientAddress?: string;
  clientTaxNumber?: string;
  issueDate: string; // YYYY-MM-DD
  dueDate: string; // YYYY-MM-DD
  currency: CurrencyCode;
  items: InvoiceItem[];
  subtotal: number;
  taxTotal: number;
  discountPercentage?: number;
  discountAmount?: number;
  total: number;
  amountPaid: number;
  balanceDue: number;
  status: InvoiceStatus;
  notes?: string;
  paymentTerms?: string;
  aiPromptOrigin?: string; // stored if generated by AI
  sentAt?: string;
  paidAt?: string;
  payments: PaymentRecord[];
  createdAt: string;
  updatedAt: string;
}

export type SubscriptionTier = 'starter' | 'professional' | 'business' | 'enterprise';

export interface SubscriptionInfo {
  userId: string; // Multi-tenant owner
  tier: SubscriptionTier;
  tierName: string;
  priceMonthly: number;
  billingInterval: 'monthly' | 'yearly';
  invoicesLimit: number | null; // null = unlimited
  profilesLimit: number | null;
  features: string[];
  invoicesUsedThisMonth: number;
  activeProfilesCount: number;
  renewalDate: string;
}

export interface ActivityItem {
  id: string;
  userId: string; // Multi-tenant owner
  type: 'invoice_created' | 'invoice_sent' | 'payment_received' | 'invoice_ai_generated' | 'client_added';
  title: string;
  description: string;
  timestamp: string;
  metadata?: any;
}
